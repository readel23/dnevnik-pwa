const sortedPhrases = Object.entries(englishPhrases).sort(([a], [b]) => b.length - a.length);

export function translateUiText(value: string, language: AppLanguage) {
  if (language === "ru" || !value.trim()) return value;
  let translated = value;
  for (const [russian, english] of sortedPhrases) translated = translated.replaceAll(russian, english);
  return translated;
}
